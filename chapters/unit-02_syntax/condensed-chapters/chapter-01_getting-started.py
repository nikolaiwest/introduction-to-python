# Chapter 1: Getting Started with Python
# Introduction to Python and your first program

# Your first Python program - the classic example
print("Hello, World!")

# Python as a calculator - basic arithmetic
print(2 + 3)
print(10 - 4)
print(5 * 6)
print(15 / 3)

# Python's interactive nature - variables and immediate results
x = 5
y = 10
result = x + y
print(f"x + y = {result}")

# Demonstrating Python's readability
name = "Python"
version = 3.12
print(f"Welcome to {name} {version}!")

# Interactive mode concepts (would be used in Python REPL)
# >>> 2 + 3
# 5
# >>> name = "Alice"
# >>> print(f"Hello, {name}!")
# Hello, Alice!
